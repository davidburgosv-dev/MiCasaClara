const {chromium}=require('playwright-core');
const {AxeBuilder}=require('@axe-core/playwright');
const assert=require('node:assert/strict');
const {mkdirSync}=require('node:fs');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
(async()=>{
 mkdirSync(path.join('proceso','capturas'),{recursive:true});
 const browser=await chromium.launch({channel:'chrome'});
 try {
 for(const width of [320,390,1280]){
  const context=await browser.newContext({viewport:{width,height:width===1280?900:844},acceptDownloads:true,hasTouch:width!==1280});
  const page=await context.newPage();
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const open=()=>page.goto(pathToFileURL(path.resolve('MiCasaClara.html')).href);
  const click=id=>page.locator(id).click();
  const focus=selector=>page.locator(selector).evaluate(el=>el===document.activeElement);
  const layout=async()=>{
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   assert(await page.locator('button:visible').evaluateAll(buttons=>buttons.every(b=>b.offsetWidth>=44&&b.offsetHeight>=44)));
  };
  const scan=async label=>{
   await layout();
   const report=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze();
   assert.deepEqual(report.violations.map(v=>[v.id,v.nodes.map(n=>n.target)]),[],label);
  };
  const shot=async name=>{if(width===390||width===1280)await page.screenshot({path:path.join('proceso','capturas',name+'-'+width+'.png')});};
  await open();
  await scan('inicio');
  await page.keyboard.press('Tab');
  assert(await focus('#start'));
  await page.keyboard.press('Enter');
  assert(await focus('h1'));
  await click('#next');
  assert(await focus('#error'));
  await click('[data-room="Cocina"]');
  assert.equal(await page.locator('[data-room="Cocina"]').getAttribute('aria-pressed'),'true');
  await scan('habitacion');
  await click('#next');
  await page.locator('#title').fill('Goteo bajo el lavaplatos');
  await click('#next');
  assert(await focus('#error'));
  assert.equal(await page.locator('#description').getAttribute('aria-invalid'),'true');
  await scan('validacion');
  if(width===390)await shot('validacion');
  await page.locator('#description').fill('Se junta agua al abrir la llave.');
  await page.locator('#location').fill('Debajo del lavaplatos');
  page.once('dialog',d=>d.dismiss());
  await click('[data-nav=help]');
  assert.equal(await page.locator('#description').inputValue(),'Se junta agua al abrir la llave.');
  await click('#next');
  await scan('foto');
  await page.locator('#photo').setInputFiles({name:'evidencia.png',mimeType:'image/png',buffer:Buffer.from('fixture')});
  assert.match(await page.locator('#filename').innerText(),/evidencia.png/);
  await click('#prev');
  assert.equal(await page.locator('#title').inputValue(),'Goteo bajo el lavaplatos');
  await click('#next');
  await click('#next');
  await scan('revision');
  if(width===390)await shot('revision');
  await click('#next');
  assert(await focus('h1'));
  await scan('confirmacion');
  await click('#all');
  await scan('listado');
  await click('[data-view]');
  assert.match(await page.locator('.summary').innerText(),/evidencia.png/);
  await scan('detalle');
  await shot('detalle');
  await page.reload();
  await click('[data-nav=records]');
  assert.equal(await page.locator('[data-view]').count(),1);
  const download=page.waitForEvent('download');
  await click('#export');
  assert.equal((await download).suggestedFilename(),'micasa-clara-registros.json');
  await click('[data-view]');
  page.once('dialog',d=>d.dismiss());
  await click('#remove');
  assert.equal(await page.locator('#remove').count(),1);
  page.once('dialog',d=>d.accept());
  await click('#remove');
  assert.equal(await page.locator('[data-view]').count(),0);
  await scan('lista vacia');
  await click('[data-nav=help]');
  await scan('ayuda');
  await click('#start');
  await click('[data-room="Cocina"]');
  page.once('dialog',d=>d.accept());
  await click('[data-nav=home]');
  assert.equal(await page.locator('#start').count(),1);
  assert.deepEqual(errors,[]);
  console.log('OK '+width+' px: flujo, persistencia, exportacion, borrado, navegacion, layout y axe (10 estados)');
  await context.close();
 }
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
